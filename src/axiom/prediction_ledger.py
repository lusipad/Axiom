"""Prediction-vs-verification ledger for CNC grey-box recommendations and R4/R5 holdout governance.

Bridges the gap between offline grey-box/GP predictions and post-cut shop-floor reality:

1. Pairs predicted metrics (`predictedMean`, `uncertaintyRadius`, `conservativeUpperBound`)
   for a recommended preset or parameter vector against a post-change `controller-trace`
   verification cut (`CncAlgorithmExport` or read-only R3 `MachineTelemetryTrace`).
2. Strictly separates evidence provenance into three tiers:
   - `synthetic-simulation`: generated by synthetic planners/simulators; useful for regression
     and adversarial mismatch testing, NEVER accepted as R4/R5 real-machine holdout evidence.
   - `external-controller-trace`: standalone `controller-trace` export without a sealed R3
     capture receipt; reconciles shop-floor predictions, stays `Inconclusive` for R4/R5 until
     paired with attested R3 telemetry receipts.
   - `real-machine-r3-telemetry`: adapted from a read-only R3 `MachineTelemetryTrace` with
     verified `traceContentHash`; when `>= min_real_holdout_runs` distinct traces are recorded,
     enables `Supported` or `Refuted` R4/R5 governance claims based on empirical RMSE and
     conservative upper-bound coverage.
"""

