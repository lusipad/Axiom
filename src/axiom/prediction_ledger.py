class PredictionVerificationLedger(AxiomModel):
    """Tamper-evident ledger of CNC parameter recommendations reconciled with post-cut traces."""

    schema_id: Literal["axiom.cnc-prediction-verification-ledger@1"] = Field(
        default="axiom.cnc-prediction-verification-ledger@1", alias="schemaId"
    )
    ledger_id: str = Field(alias="ledgerId", min_length=1, max_length=200)
    surrogate_model_hash: str = Field(alias="surrogateModelHash")
    controller_profile_id: str = Field(alias="controllerProfileId")
    entries: tuple[PredictionVerificationEntry, ...]
    summary: PredictionLedgerSummary
    ledger_content_hash: str = Field(alias="ledgerContentHash")


def _verify_surrogate_hash(surrogate: LearnedParameterSurrogate) -> None:
    content = surrogate.model_dump(mode="json", by_alias=True, exclude_none=True)
    content.pop("modelContentHash", None)
    if _canonical_hash(content) != surrogate.model_content_hash:
        raise ValueError("surrogate modelContentHash does not match surrogate payload")


def _verify_recommendation_hash(report: ParameterRecommendationReport) -> None:
    content = report.model_dump(mode="json", by_alias=True, exclude_none=True)
    content.pop("reportContentHash", None)
    if _canonical_hash(content) != report.report_content_hash:
        raise ValueError("recommendationReport reportContentHash does not match report payload")


def _select_candidate(
    report: ParameterRecommendationReport,
    candidate_id: str | None,
) -> ParameterRecommendationCandidate:
    all_cands = (*report.presets, *report.pareto_front)
    if not all_cands:
        raise ValueError("recommendation_report contains no feasible candidates to verify")
    if candidate_id is None:
        for c in report.presets:
            if c.preset_role == "PrecisionOptimal":
                return c
        return all_cands[0]
    for c in all_cands:
        if c.candidate_id == candidate_id:
            return c
    raise KeyError(f"candidate_id '{candidate_id}' not found in recommendation_report")


def record_prediction_verification(
    case: CncBenchmarkCase,
    surrogate: LearnedParameterSurrogate,
    verification_trace: CncAlgorithmExport | MachineTelemetryTrace,
    *,
    recommendation_report: ParameterRecommendationReport | None = None,
    candidate_id: str | None = None,
    applied_parameters: Mapping[str, float] | None = None,
    baseline_trace_or_report: CncAlgorithmExport | CncQualityReport | None = None,
    safety_kappa: float = 1.0,
    entry_id: str = "verify.001",
    r3_algorithm_id: str = "axiom.r3-observed-controller",
) -> PredictionVerificationEntry:
    """Evaluate a post-cut trace and seal a `PredictionVerificationEntry` against predictions."""
    _verify_surrogate_hash(surrogate)
    if recommendation_report is not None:
        _verify_recommendation_hash(recommendation_report)
        if recommendation_report.surrogate_model_hash != surrogate.model_content_hash:
            raise ValueError("recommendation_report.surrogateModelHash does not match surrogate.modelContentHash")

    cand: ParameterRecommendationCandidate | None = None
    if recommendation_report is not None and applied_parameters is None:
        cand = _select_candidate(recommendation_report, candidate_id)
        params_dict = {k: float(v) for k, v in cand.full_parameters.items()}
        resolved_cand_id = cand.candidate_id
    elif applied_parameters is not None:
        params_dict = {k: float(v) for k, v in applied_parameters.items()}
        resolved_cand_id = candidate_id or "manual.parameters"
    else:
        raise ValueError("either `recommendation_report` or `applied_parameters` must be provided")

    # Resolve verification trace & provenance tier
    r3_receipt_id: str | None = None
    r3_device_id: str | None = None
    r3_trace_hash: str | None = None
    if isinstance(verification_trace, MachineTelemetryTrace):
        from .cnc_governance import adapt_r3_telemetry_to_cnc_export

        r3_trace_hash = machine_trace_content_hash(verification_trace)
        if r3_trace_hash != verification_trace.capture_receipt.trace_content_hash:
            raise ValueError("R3 captureReceipt.traceContentHash does not match telemetry payload")
        r3_receipt_id = verification_trace.capture_receipt.receipt_id
        r3_device_id = verification_trace.device_identity.device_id
        export_obj = adapt_r3_telemetry_to_cnc_export(
            verification_trace,
            case,
            algorithm_id=r3_algorithm_id,
            parameters=params_dict,
        )
        if export_obj.source_kind != "controller-trace":
            raise ValueError("holdout verification requires dual command+actual controller-trace feedback")
        if _is_synthetic_export(export_obj):
            origin: LedgerEvidenceOrigin = "synthetic-simulation"
        else:
            origin = "real-machine-r3-telemetry"
    else:
        export_obj = verification_trace
        if export_obj.source_kind != "controller-trace":
            raise ValueError(
                f"verification export must have sourceKind='controller-trace' with actual feedback, "
                f"got '{export_obj.source_kind}'"
            )
        origin = "synthetic-simulation" if _is_synthetic_export(export_obj) else "external-controller-trace"

    observed_report = evaluate_cnc_export(case, export_obj)
    if observed_report.servo_metrics is None:
        raise ValueError("verification export is missing servoMetrics (actualPositionMm feedback required)")

    baseline_report: CncQualityReport | None = None
    if isinstance(baseline_trace_or_report, CncQualityReport):
        baseline_report = baseline_trace_or_report
    elif isinstance(baseline_trace_or_report, CncAlgorithmExport):
        baseline_report = evaluate_cnc_export(case, baseline_trace_or_report)

    metric_records: dict[str, MetricVerificationRecord] = {}
    any_ood = False
    for m_id in LEDGER_TRACKED_METRICS:
        obs_pair = _extract_observed_metric(observed_report, m_id)
        if obs_pair is None or m_id not in surrogate.metric_heads:
            continue
        obs_val, obs_unit = obs_pair
        if cand is not None and m_id in cand.predicted_metrics and cand.in_domain is not None:
            pm = cand.predicted_metrics[m_id]
            pred_mean = float(pm.predicted_mean)
            pred_rad = float(pm.uncertainty_radius)
            upper_b = float(pm.conservative_upper_bound)
            if not cand.in_domain:
                any_ood = True
        else:
            pred_mean, pred_rad, m_ood = predict_metric_for_parameters(
                surrogate, m_id, params_dict, target_case=case
            )
            if m_ood:
                any_ood = True
            upper_b = pred_mean + safety_kappa * pred_rad

        base_obs_val: float | None = None
        improved: bool | None = None
        if baseline_report is not None:
            b_pair = _extract_observed_metric(baseline_report, m_id)
            if b_pair is not None:
                base_obs_val = round(float(b_pair[0]), 6)
                improved = bool(obs_val < float(b_pair[0]) - 1e-9)

        err = obs_val - pred_mean
        abs_err = abs(err)
        rel_pct = (abs_err / max(abs(obs_val), 1e-6)) * 100.0
        within_b = bool(obs_val <= upper_b + 1e-9)
        metric_records[m_id] = MetricVerificationRecord(
            metricId=m_id,
            unit=obs_unit,
            baselineObserved=base_obs_val,
            predictedMean=round(pred_mean, 6),
            uncertaintyRadius=round(pred_rad, 6),
            conservativeUpperBound=round(upper_b, 6),
            observedValue=round(obs_val, 6),
            predictionError=round(err, 6),
            absError=round(abs_err, 6),
            relativeErrorPct=round(rel_pct, 3),
            withinConservativeBound=within_b,
            improvedOverBaseline=improved,
        )

    audited_present = [metric_records[m] for m in AUDITED_BOUND_METRICS if m in metric_records]
    if not audited_present:
        raise ValueError("no overlap between surrogate metricHeads and observed audited metrics")
    all_bounds_ok = all(r.within_conservative_bound for r in audited_present)
    in_domain_flag = (cand.in_domain if cand is not None else (not any_ood))

    entry = PredictionVerificationEntry(
        entryId=entry_id,
        caseId=case.case_id,
        caseContentHash=benchmark_case_hash(case),
        surrogateModelHash=surrogate.model_content_hash,
        recommendationReportHash=(
            recommendation_report.report_content_hash if recommendation_report is not None else None
        ),
        candidateId=resolved_cand_id,
        inDomain=bool(in_domain_flag),
        safetyKappa=safety_kappa,
        evidenceOrigin=origin,
        r3ReceiptId=r3_receipt_id,
        r3DeviceId=r3_device_id,
        r3TraceContentHash=r3_trace_hash,
        verificationExportHash=observed_report.analysis.export_content_hash,
        observedReportHash=observed_report.report_content_hash,
        appliedParameters=params_dict,
        metricRecords=metric_records,
        allConservativeBoundsHeld=all_bounds_ok,
        entryContentHash="",
    )
    content = entry.model_dump(mode="json", by_alias=True, exclude_none=True)
    content.pop("entryContentHash", None)
    return entry.model_copy(update={"entry_content_hash": _canonical_hash(content)})


def summarize_prediction_entries(
    entries: Sequence[PredictionVerificationEntry],
) -> PredictionLedgerSummary:
    """Compute aggregate RMSE, MAPE, empirical bound coverage, and improvement rates."""
    n_total = len(entries)
    real_r3 = [e for e in entries if e.evidence_origin == "real-machine-r3-telemetry"]
    ext_tr = [e for e in entries if e.evidence_origin == "external-controller-trace"]
    synth = [e for e in entries if e.evidence_origin == "synthetic-simulation"]
    distinct_r3 = len({e.r3_trace_content_hash for e in real_r3 if e.r3_trace_content_hash})

    # If real R3 entries exist, compute accuracy/coverage over real R3 entries when summarizing?
    # Better: compute over ALL entries when uniform, or when mixed/real exist, summarize all entries here
    # while governance evaluates specifically over verified `real-machine-r3-telemetry` entries!
    dur_sq: list[float] = []
    dur_ape: list[float] = []
    cmd_sq: list[float] = []
    act_sq: list[float] = []
    bound_checks = 0
    bound_hits = 0
    entry_hits = 0
    dur_imp: list[bool] = []
    acc_imp: list[bool] = []

    for e in entries:
        if e.all_conservative_bounds_held:
            entry_hits += 1
        if "durationSeconds" in e.metric_records:
            r_d = e.metric_records["durationSeconds"]
            dur_sq.append(r_d.prediction_error ** 2)
            dur_ape.append(r_d.relative_error_pct)
            if r_d.improved_over_baseline is not None:
                dur_imp.append(r_d.improved_over_baseline)
        if "sampledPathDeviationMaxMm" in e.metric_records:
            r_c = e.metric_records["sampledPathDeviationMaxMm"]
            cmd_sq.append(r_c.prediction_error ** 2)
        if "actualPathDeviationMaxMm" in e.metric_records:
            r_a = e.metric_records["actualPathDeviationMaxMm"]
            act_sq.append(r_a.prediction_error ** 2)
            if r_a.improved_over_baseline is not None:
                acc_imp.append(r_a.improved_over_baseline)
        for m_b in AUDITED_BOUND_METRICS:
            if m_b in e.metric_records:
                bound_checks += 1
                if e.metric_records[m_b].within_conservative_bound:
                    bound_hits += 1

    return PredictionLedgerSummary(
        totalEntryCount=n_total,
        realR3EntryCount=len(real_r3),
        externalTraceEntryCount=len(ext_tr),
        syntheticEntryCount=len(synth),
        distinctRealR3TraceCount=distinct_r3,
        allInDomain=all(e.in_domain for e in entries) if entries else True,
        durationRmseS=round(math.sqrt(sum(dur_sq) / len(dur_sq)), 6) if dur_sq else None,
        durationMapePct=round(sum(dur_ape) / len(dur_ape), 3) if dur_ape else None,
        commandDeviationRmseMm=round(math.sqrt(sum(cmd_sq) / len(cmd_sq)), 6) if cmd_sq else None,
        actualDeviationRmseMm=round(math.sqrt(sum(act_sq) / len(act_sq)), 6) if act_sq else None,
        conservativeBoundCheckCount=bound_checks,
        conservativeBoundHitCount=bound_hits,
        empiricalCoverageRate=round(bound_hits / bound_checks, 4) if bound_checks > 0 else None,
        entryLevelCoverageRate=round(entry_hits / n_total, 4) if n_total > 0 else None,
        cycleTimeImprovementRate=round(sum(dur_imp) / len(dur_imp), 4) if dur_imp else None,
        accuracyImprovementRate=round(sum(acc_imp) / len(acc_imp), 4) if acc_imp else None,
    )


def build_prediction_verification_ledger(
    entries: Sequence[PredictionVerificationEntry],
    *,
    surrogate: LearnedParameterSurrogate | None = None,
    surrogate_model_hash: str | None = None,
    controller_profile_id: str | None = None,
    ledger_id: str = "cnc.prediction-ledger@1",
) -> PredictionVerificationLedger:
    """Seal a `PredictionVerificationLedger` over one or more verification entries."""
    resolved_hash = (
        surrogate.model_content_hash
        if surrogate is not None
        else (surrogate_model_hash or (entries[0].surrogate_model_hash if entries else ""))
    )
    if not resolved_hash:
        raise ValueError("surrogate or surrogate_model_hash is required to build an empty ledger")
    for e in entries:
        verify_prediction_entry_integrity(e, expected_surrogate_hash=resolved_hash)

    prof_id = (
        controller_profile_id
        or (
            surrogate.controller_profile.profile_id
            if (surrogate is not None and surrogate.controller_profile is not None)
            else "generic-fir-biquad@1"
        )
    )
    summary = summarize_prediction_entries(entries)
    ledger = PredictionVerificationLedger(
        ledgerId=ledger_id,
        surrogateModelHash=resolved_hash,
        controllerProfileId=prof_id,
        entries=tuple(entries),
        summary=summary,
        ledgerContentHash="",
    )
    content = ledger.model_dump(mode="json", by_alias=True, exclude_none=True)
    content.pop("ledgerContentHash", None)
    return ledger.model_copy(update={"ledger_content_hash": _canonical_hash(content)})


def append_prediction_verification_entry(
    ledger: PredictionVerificationLedger,
    entry: PredictionVerificationEntry,
) -> PredictionVerificationLedger:
    """Verify an existing ledger + new entry, and return a newly sealed ledger with `entry` appended."""
    verify_prediction_ledger_integrity(ledger)
    verify_prediction_entry_integrity(entry, expected_surrogate_hash=ledger.surrogate_model_hash)
    return build_prediction_verification_ledger(
        (*ledger.entries, entry),
        surrogate_model_hash=ledger.surrogate_model_hash,
        controller_profile_id=ledger.controller_profile_id,
        ledger_id=ledger.ledger_id,
    )


def verify_prediction_entry_integrity(
    entry: PredictionVerificationEntry,
    *,
    expected_surrogate_hash: str | None = None,
) -> None:
    """Raise `ValueError` if an entry's content hash or surrogate binding was tampered with."""
    content = entry.model_dump(mode="json", by_alias=True, exclude_none=True)
    content.pop("entryContentHash", None)
    expected_entry_hash = _canonical_hash(content)
    if entry.entry_content_hash != expected_entry_hash:
        raise ValueError(f"entry '{entry.entry_id}' entryContentHash mismatch")
    if expected_surrogate_hash is not None and entry.surrogate_model_hash != expected_surrogate_hash:
        raise ValueError(
            f"entry '{entry.entry_id}' surrogateModelHash does not match expected surrogate ({expected_surrogate_hash[:12]}...)"
        )
    if entry.evidence_origin == "real-machine-r3-telemetry" and not entry.r3_trace_content_hash:
        raise ValueError(f"entry '{entry.entry_id}' claims real-machine-r3-telemetry without r3TraceContentHash")


def verify_prediction_ledger_integrity(
    ledger: PredictionVerificationLedger,
    *,
    expected_surrogate_hash: str | None = None,
) -> None:
    """Raise `ValueError` if the ledger or any entry fails hash or summary consistency checks."""
    content = ledger.model_dump(mode="json", by_alias=True, exclude_none=True)
    content.pop("ledgerContentHash", None)
    if ledger.ledger_content_hash != _canonical_hash(content):
        raise ValueError(f"ledger '{ledger.ledger_id}' ledgerContentHash mismatch")
    if expected_surrogate_hash is not None and ledger.surrogate_model_hash != expected_surrogate_hash:
        raise ValueError("ledger.surrogateModelHash does not match surrogate.modelContentHash")
    for e in ledger.entries:
        verify_prediction_entry_integrity(e, expected_surrogate_hash=ledger.surrogate_model_hash)
    recomputed = summarize_prediction_entries(ledger.entries)
    if recomputed != ledger.summary:
        raise ValueError("ledger.summary does not match recomputed statistics over ledger.entries")


def _pad(text: str, width: int, *, right: bool = False) -> str:
    shown = sum(2 if unicodedata.east_asian_width(char) in "WF" else 1 for char in text)
    fill = " " * max(width - shown, 1 if right else 0)
    return fill + text if right else text + fill


def render_prediction_ledger_table(ledger: PredictionVerificationLedger) -> str:
    """Render a concise shop-floor reconciliation table comparing predicted bounds vs actual cuts."""
    s = ledger.summary
    cov_str = f"{s.empirical_coverage_rate * 100:.1f}%" if s.empirical_coverage_rate is not None else "N/A"
    lines = [
        f"【预测-实测对账单】{ledger.ledger_id}（控制器：{ledger.controller_profile_id}）",
        (
            f"总核验刀次：{s.total_entry_count} | R3 实机回执：{s.real_r3_entry_count}（独立轨迹 {s.distinct_real_r3_trace_count}）"
            f" | 外部控制器轨迹：{s.external_trace_entry_count} | 仿真回放：{s.synthetic_entry_count}"
        ),
        (
            f"保守上界命中率：{cov_str} ({s.conservative_bound_hit_count}/{s.conservative_bound_check_count})"
            f" | 周期 MAPE：{s.duration_mape_pct if s.duration_mape_pct is not None else 'N/A'}%"
            f" | 实测轮廓 RMSE：{s.actual_deviation_rmse_mm if s.actual_deviation_rmse_mm is not None else 'N/A'} mm"
        ),
        "",
    ]
    for e in ledger.entries:
        lines.append(
            f"  [{e.entry_id}] 案例={e.case_id} | 档位={e.candidate_id} | 证据源={e.evidence_origin}"
            f" | 全部上界守住={'是' if e.all_conservative_bounds_held else '否'}"
        )
        lines.append(
            "    "
            + _pad("指标ID", 28)
            + _pad("预测均值", 12, right=True)
            + _pad("保守上界", 12, right=True)
            + _pad("实测值", 12, right=True)
            + _pad("偏差", 12, right=True)
            + _pad("守住上界", 10, right=True)
        )
        for m_id, rec in e.metric_records.items():
            lines.append(
                "    "
                + _pad(m_id, 28)
                + _pad(f"{rec.predicted_mean:.5g}", 12, right=True)
                + _pad(f"{rec.conservative_upper_bound:.5g}", 12, right=True)
                + _pad(f"{rec.observed_value:.5g}", 12, right=True)
                + _pad(f"{rec.prediction_error:+.4g}", 12, right=True)
                + _pad("OK" if rec.within_conservative_bound else "MISS", 10, right=True)
            )
    return "\n".join(lines) + "\n"
