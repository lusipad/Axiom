LedgerEvidenceOrigin = Literal[
    "real-machine-r3-telemetry",
    "external-controller-trace",
    "synthetic-simulation",
]

AUDITED_BOUND_METRICS: tuple[str, ...] = (
    "durationSeconds",
    "sampledPathDeviationMaxMm",
    "actualPathDeviationMaxMm",
)

LEDGER_TRACKED_METRICS: tuple[str, ...] = (
    "durationSeconds",
    "sampledPathDeviationMaxMm",
    "actualPathDeviationMaxMm",
    "followingErrorMaxMm",
    "quadrantGlitchExcessMm",
)

_SYNTHETIC_ALGORITHM_IDS: frozenset[str] = frozenset(
    {
        "axiom.realistic-cnc-planner",
        "example.planner",
    }
)


def _canonical_hash(payload: AxiomModel | Mapping[str, Any]) -> str:
    data = (
        payload.model_dump(mode="json", by_alias=True, exclude_none=True)
        if isinstance(payload, AxiomModel)
        else dict(payload)
    )
    raw = json.dumps(data, sort_keys=True, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def _is_synthetic_export(export: CncAlgorithmExport) -> bool:
    if export.source_kind != "controller-trace":
        return True
    alg_id = export.algorithm_id.strip()
    alg_ver = export.algorithm_version.strip().lower()
    if alg_id in _SYNTHETIC_ALGORITHM_IDS:
        return True
    if "synthetic" in alg_id.lower() or "realistic-cnc-kernel" in alg_ver or "simulator" in alg_id.lower():
        return True
    return False


def _extract_observed_metric(report: CncQualityReport, metric_id: str) -> tuple[float, str] | None:
    if metric_id in report.analysis.metrics:
        m = report.analysis.metrics[metric_id]
        if m.value is not None:
            return float(m.value), m.unit
    if report.servo_metrics and metric_id in report.servo_metrics:
        sm = report.servo_metrics[metric_id]
        if sm.value is not None:
            return float(sm.value), sm.unit
    if metric_id in report.kinematic_summary:
        unit_Guess = "s" if "Seconds" in metric_id else "mm"
        return float(report.kinematic_summary[metric_id]), unit_Guess
    return None


class MetricVerificationRecord(AxiomModel):
    """Predicted-vs-observed reconciliation for one metric on one verification cut."""

    metric_id: str = Field(alias="metricId")
    unit: str
    baseline_observed: float | None = Field(default=None, alias="baselineObserved")
    predicted_mean: float = Field(alias="predictedMean")
    uncertainty_radius: float = Field(alias="uncertaintyRadius")
    conservative_upper_bound: float = Field(alias="conservativeUpperBound")
    observed_value: float = Field(alias="observedValue")
    prediction_error: float = Field(alias="predictionError")
    abs_error: float = Field(alias="absError")
    relative_error_pct: float = Field(alias="relativeErrorPct")
    within_conservative_bound: bool = Field(alias="withinConservativeBound")
    improved_over_baseline: bool | None = Field(default=None, alias="improvedOverBaseline")


